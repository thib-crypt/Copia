import AppKit

struct PasteboardSnapshot {
    var text: String
    var types: Set<String>
    var markerSource: String?
    var frontmost: NSRunningApplication?

    var isConcealed: Bool { types.contains("org.nspasteboard.ConcealedType") }
    var isTransient: Bool { types.contains("org.nspasteboard.TransientType") }
    var isAutoGenerated: Bool { types.contains("org.nspasteboard.AutoGeneratedType") }
}

/// Surveille le presse-papier avec le minimum d'énergie :
/// - lit seulement `changeCount` (appel très léger) ;
/// - timer avec tolérance, pour que macOS regroupe les réveils ;
/// - ralentit après 2 min d'inactivité ;
/// - s'arrête pendant la veille, l'écran éteint et la session verrouillée.
final class PasteboardWatcher {
    var onChange: ((PasteboardSnapshot) -> Void)?

    private let pb = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var currentInterval: TimeInterval = 0
    private var lastActivity = Date.now
    private var suspended = false
    private var ignoredChangeCount: Int?
    private var observers: [NSObjectProtocol] = []

    var baseInterval: TimeInterval { didSet { if !suspended { schedule(baseInterval) } } }
    private var idleInterval: TimeInterval { min(baseInterval * 1.6, 0.6) }
    private static let idleDelay: TimeInterval = 120

    /// Nombre de vérifications par seconde actuellement (pour l'écran Performance).
    var checksPerSecond: Double { suspended || timer == nil ? 0 : 1 / currentInterval }

    init(interval: TimeInterval) {
        baseInterval = interval
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        lastChangeCount = pb.changeCount
        installObservers()
        schedule(baseInterval)
    }

    /// Ignore le prochain changement si c'est Copia qui vient d'écrire.
    func ignore(changeCount: Int) { ignoredChangeCount = changeCount }

    // MARK: - Timer

    private func schedule(_ interval: TimeInterval) {
        timer?.invalidate()
        currentInterval = interval
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        t.tolerance = interval * 0.4
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func suspend() {
        suspended = true
        timer?.invalidate()
        timer = nil
    }

    private func resume() {
        guard suspended else { return }
        suspended = false
        tick()
        schedule(baseInterval)
    }

    private func tick() {
        let c = pb.changeCount
        guard c != lastChangeCount else {
            if currentInterval < idleInterval, Date.now.timeIntervalSince(lastActivity) > Self.idleDelay {
                schedule(idleInterval)
            }
            return
        }
        lastChangeCount = c
        lastActivity = .now
        if currentInterval != baseInterval { schedule(baseInterval) }
        if c == ignoredChangeCount { ignoredChangeCount = nil; return }
        if let snap = readSnapshot() { onChange?(snap) }
    }

    private func readSnapshot() -> PasteboardSnapshot? {
        let types = Set((pb.types ?? []).map(\.rawValue))
        // Phase 2 : images / fichiers. Pour l'instant, texte uniquement.
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        let marker = pb.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source"))
        let capped = text.utf16.count > 2_000_000 ? String(text.prefix(2_000_000)) : text
        return PasteboardSnapshot(text: capped, types: types, markerSource: marker,
                                  frontmost: NSWorkspace.shared.frontmostApplication)
    }

    // MARK: - Veille / verrouillage

    private func installObservers() {
        let ws = NSWorkspace.shared.notificationCenter
        let dnc = DistributedNotificationCenter.default()
        let pause: (Notification) -> Void = { [weak self] _ in MainActor.assumeIsolated { self?.suspend() } }
        let play: (Notification) -> Void = { [weak self] _ in MainActor.assumeIsolated { self?.resume() } }
        for name in [NSWorkspace.willSleepNotification, NSWorkspace.screensDidSleepNotification,
                     NSWorkspace.sessionDidResignActiveNotification] {
            observers.append(ws.addObserver(forName: name, object: nil, queue: .main, using: pause))
        }
        for name in [NSWorkspace.didWakeNotification, NSWorkspace.screensDidWakeNotification,
                     NSWorkspace.sessionDidBecomeActiveNotification] {
            observers.append(ws.addObserver(forName: name, object: nil, queue: .main, using: play))
        }
        observers.append(dnc.addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main, using: pause))
        observers.append(dnc.addObserver(forName: .init("com.apple.screenIsUnlocked"), object: nil, queue: .main, using: play))
    }
}
