import Foundation

/// Ce que l'on sait d'un changement du presse-papier.
nonisolated struct ClipSignal: Sendable {
    var hash: String
    var time: TimeInterval
    var isTransient = false
    var isConcealed = false
    var isAutoGenerated = false
    /// Valeur de `org.nspasteboard.source` (bundle id de l'app qui a écrit), si fournie.
    var markerSource: String? = nil
    /// App au premier plan au moment de la copie.
    var frontmostBundle: String? = nil
}

nonisolated struct DedupConfig: Sendable, Equatable {
    var smartDictation = true
    var dictationWindow: TimeInterval = 4
    var dictationApps: Set<String> = []
    var bumpOnRestore = false
    var keepDictations = true
    var mergeDuplicates = true
    var ignoreConcealed = true
    var respectTransient = true
    var excludedApps: Set<String> = []
}

nonisolated enum IgnoreReason: Sendable, Equatable {
    case concealed, transient, excludedApp, sameAsCurrent, dictationDiscarded
}

nonisolated enum CaptureAction: Sendable, Equatable {
    /// Rien n'est enregistré.
    case ignore(IgnoreReason)
    /// Nouveau clip.
    case insert(isDictation: Bool)
    /// Clip identique existant : on le remonte en haut (fusion).
    case bump(markDictation: Bool)
    /// Doublon conservé volontairement (fusion désactivée).
    case insertDuplicate
    /// L'app de dictée a restauré l'ancien presse-papier : on ne touche pas à l'historique.
    /// `dictationHash` = le texte dicté juste avant, à badger « Dictée ».
    case silentRestore(dictationHash: String?)
}

/// Décide quoi faire de chaque changement du presse-papier.
/// Logique pure, testée dans CopiaTests.
nonisolated struct DedupEngine: Sendable {
    var config: DedupConfig

    private(set) var current: (hash: String, time: TimeInterval)?
    private(set) var previous: (hash: String, time: TimeInterval)?

    init(config: DedupConfig) { self.config = config }

    mutating func decide(_ s: ClipSignal, existsInHistory: Bool) -> CaptureAction {
        if let cur = current, cur.hash == s.hash {
            // Même contenu réécrit (ou changement intermédiaire manqué) : rien à faire.
            return .ignore(.sameAsCurrent)
        }
        let action = evaluate(s, existsInHistory: existsInHistory)
        advance(hash: s.hash, time: s.time)
        return action
    }

    /// Copia vient lui-même d'écrire dans le presse-papier.
    mutating func noteOwnWrite(hash: String, time: TimeInterval) {
        advance(hash: hash, time: time)
    }

    private mutating func advance(hash: String, time: TimeInterval) {
        guard current?.hash != hash else { return }
        previous = current
        current = (hash, time)
    }

    private func evaluate(_ s: ClipSignal, existsInHistory: Bool) -> CaptureAction {
        if config.ignoreConcealed && s.isConcealed { return .ignore(.concealed) }
        if let src = s.markerSource, config.excludedApps.contains(src) { return .ignore(.excludedApp) }
        if let front = s.frontmostBundle, config.excludedApps.contains(front) { return .ignore(.excludedApp) }

        let fromDictationApp = s.markerSource.map { config.dictationApps.contains($0) } ?? false

        if config.smartDictation {
            // Motif A → B → A rapide : restauration par l'outil de dictée.
            if let prev = previous, let cur = current,
               prev.hash == s.hash,
               s.time - cur.time <= config.dictationWindow {
                return config.bumpOnRestore ? .bump(markDictation: false) : .silentRestore(dictationHash: cur.hash)
            }
            // Réécriture marquée « auto-générée » / venant de l'app de dictée d'un texte déjà connu.
            if (fromDictationApp || s.isAutoGenerated) && existsInHistory {
                return config.bumpOnRestore ? .bump(markDictation: false) : .silentRestore(dictationHash: nil)
            }
        }

        if config.respectTransient && s.isTransient { return .ignore(.transient) }

        if config.smartDictation && fromDictationApp {
            guard config.keepDictations else { return .ignore(.dictationDiscarded) }
            return existsInHistory ? .bump(markDictation: true) : .insert(isDictation: true)
        }

        if existsInHistory {
            return config.mergeDuplicates ? .bump(markDictation: false) : .insertDuplicate
        }
        return .insert(isDictation: false)
    }
}
