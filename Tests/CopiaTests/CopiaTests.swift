import XCTest

final class DedupEngineTests: XCTestCase {
    private func engine(_ configure: (inout DedupConfig) -> Void = { _ in }) -> DedupEngine {
        var c = DedupConfig()
        c.dictationApps = ["com.prakashjoshipax.VoiceInk"]
        configure(&c)
        return DedupEngine(config: c)
    }

    /// Le cas VoiceInk : A copié, dictée B collée, A restauré 1 s après.
    func testVoiceInkRestoreIsSilenced() {
        var e = engine()
        XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false), .insert(isDictation: false))
        XCTAssertEqual(e.decide(ClipSignal(hash: "B", time: 10), existsInHistory: false), .insert(isDictation: false))
        XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: 11), existsInHistory: true), .silentRestore(dictationHash: "B"))
    }

    func testVoiceInkMarkersTagDictation() {
        var e = engine()
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        let b = ClipSignal(hash: "B", time: 10, isAutoGenerated: true, markerSource: "com.prakashjoshipax.VoiceInk")
        XCTAssertEqual(e.decide(b, existsInHistory: false), .insert(isDictation: true))
        // Restauration tardive (hors fenêtre) mais marquée par VoiceInk : toujours ignorée.
        let restore = ClipSignal(hash: "A", time: 30, isAutoGenerated: true, markerSource: "com.prakashjoshipax.VoiceInk")
        XCTAssertEqual(e.decide(restore, existsInHistory: true), .silentRestore(dictationHash: nil))
    }

    func testSlowRecopyIsNormalBump() {
        var e = engine()
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        _ = e.decide(ClipSignal(hash: "B", time: 10), existsInHistory: false)
        XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: 60), existsInHistory: true), .bump(markDictation: false))
    }

    func testRepeatedDictationsNeverDuplicate() {
        var e = engine()
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        for i in 1...5 {
            let t = Double(i) * 100
            _ = e.decide(ClipSignal(hash: "D\(i)", time: t), existsInHistory: false)
            XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: t + 1), existsInHistory: true),
                           .silentRestore(dictationHash: "D\(i)"))
        }
    }

    func testSmartDisabledFallsBackToMerge() {
        var e = engine { $0.smartDictation = false }
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        _ = e.decide(ClipSignal(hash: "B", time: 1), existsInHistory: false)
        XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: 2), existsInHistory: true), .bump(markDictation: false))
    }

    func testMergeDisabledKeepsDuplicates() {
        var e = engine { $0.smartDictation = false; $0.mergeDuplicates = false }
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        _ = e.decide(ClipSignal(hash: "B", time: 1), existsInHistory: false)
        XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: 2), existsInHistory: true), .insertDuplicate)
    }

    func testPrivacy() {
        var e = engine { $0.excludedApps = ["com.1password.1password"] }
        XCTAssertEqual(e.decide(ClipSignal(hash: "P", time: 0, isConcealed: true), existsInHistory: false), .ignore(.concealed))
        XCTAssertEqual(e.decide(ClipSignal(hash: "Q", time: 1, frontmostBundle: "com.1password.1password"), existsInHistory: false),
                       .ignore(.excludedApp))
        XCTAssertEqual(e.decide(ClipSignal(hash: "T", time: 2, isTransient: true), existsInHistory: false), .ignore(.transient))
    }

    func testSameContentRewriteIgnored() {
        var e = engine()
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        XCTAssertEqual(e.decide(ClipSignal(hash: "A", time: 0.5), existsInHistory: true), .ignore(.sameAsCurrent))
    }

    func testOwnWriteThenRestore() {
        var e = engine()
        _ = e.decide(ClipSignal(hash: "A", time: 0), existsInHistory: false)
        e.noteOwnWrite(hash: "X", time: 50)      // collage depuis Copia
        _ = e.decide(ClipSignal(hash: "D", time: 60), existsInHistory: false)
        XCTAssertEqual(e.decide(ClipSignal(hash: "X", time: 61), existsInHistory: true), .silentRestore(dictationHash: "D"))
    }
}

final class FuzzySearchTests: XCTestCase {
    private func cands(_ texts: [String]) -> [SearchCandidate] {
        texts.enumerated().map { i, t in
            SearchCandidate(id: Int64(i), key: TextNormalizer.searchKey(for: t), recency: 0, pinned: false)
        }
    }

    func testAccentsAndCase() {
        let hits = FuzzySearch.search("ELEVE", in: cands(["Réunion des élèves demain", "autre chose"]))
        XCTAssertEqual(hits.map(\.id), [0])
    }

    func testWordsInAnyOrder() {
        let hits = FuzzySearch.search("hotfix ota", in: cands(["npm run ota:hotfix", "npm run build"]))
        XCTAssertEqual(hits.map(\.id), [0])
    }

    func testTypoTolerance() {
        let hits = FuzzySearch.search("transcirption", in: cands(["La transcription audio est prête", "Rien à voir"]))
        XCTAssertEqual(hits.first?.id, 0)
    }

    func testSubsequence() {
        let hits = FuzzySearch.search("trnscr", in: cands(["transcription", "tournesol"]))
        XCTAssertEqual(hits.first?.id, 0)
    }

    func testExactBeatsFuzzy() {
        let hits = FuzzySearch.search("chat", in: cands(["un chapeau tout neuf", "le chat dort"]))
        XCTAssertEqual(hits.first?.id, 1)
    }

    func testNoFalsePositive() {
        XCTAssertTrue(FuzzySearch.search("kubernetes", in: cands(["bonjour", "merci beaucoup"])).isEmpty)
    }

    func testPerformance5000() {
        let base = (0..<5000).map { "Copie numéro \($0) avec un peu de texte pour la recherche floue \($0 * 7)" }
        let c = cands(base)
        measure { _ = FuzzySearch.search("recherhce flou", in: c) }
    }
}
